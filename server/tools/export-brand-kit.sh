#!/usr/bin/env bash
# Write the brand kit (icon, mark, wordmark, colours as plain files) to brand/ in the Taviri repository,
# for the phone app and the browser extension. The files come out of the vault image, so they are
# exactly what the web vault shows. Run after changing stack/image/brand.env or the SVGs and deploying.
set -euo pipefail
here=$(cd "$(dirname "$0")/.." && pwd)
. "$here/mac/common.sh"
out=${1:-$(cd "$(dirname "$0")/../.." && pwd)/brand}
mkdir -p "$out"
pi '. /etc/pi-vault/site.env && docker run --rm --entrypoint tar "pi-vault/vault:$VW_VERSION" -C /brand/kit -cf - .' | tar -C "$out" -xf -
cat > "$out/README.md" <<'KIT'
# Taviri brand kit

Generated by `server/tools/export-brand-kit.sh`. Do not edit here: change the
sources in `server/stack/image/` (`brand.env`, `icon.svg`, `mark.svg`, `glyph.svg`),
deploy, and export again.

**The artwork is a placeholder** drawn for the server (a keyhole: Taviri is Tahitian for
"key"). It stays until the owner approves it or supplies a real one.

| File | What | Use |
| --- | --- | --- |
| `brand.json` | name, tagline, colour (#RRGGBB), ink colour | read this for values |
| `icon.svg`, `icon-48.png` … `icon-1024.png` | colour app icon: white keyhole on a rounded square in the brand colour | app icons, favicons |
| `glyph.svg` | the keyhole alone, one colour, 64 x 64 | adaptive-icon foreground, themed icons, status bar |
| `mark.svg` | rounded square with the keyhole cut out, one colour | one-colour logos (toolbars, sidebars) |
| `wordmark.svg` | the name as outlines (Inter, weight 650), no font needed | next to the mark |
| `logo.svg`, `logo-white.svg`, `logo.png` | mark + wordmark, for light and dark backgrounds | headers, store listings |

The web vault turns the stock blue into the brand colour by rotating every blue to the brand hue
and keeping its lightness (OKLCH), the same way the Android app does (`hue=172`).
KIT
ls "$out"
